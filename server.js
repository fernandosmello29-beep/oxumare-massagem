function limparDocumento(valor) {
    return String(valor || "").replace(/\D/g, "");
}

const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: { rejectUnauthorized: false },
    max: 5
});

// Faz o PostgreSQL devolver NUMERIC como número JavaScript.
types.setTypeParser(1700, value => Number(value));

function converterPlaceholders(sql) {
    let indice = 0;
    return sql.replace(/\?/g, () => `$${++indice}`);
}

class DatabaseAdapter {
    prepare(sql) {
        const consulta = converterPlaceholders(sql);

        return {
            get: async (...params) => {
                const resultado = await pool.query(consulta, params);
                return resultado.rows[0];
            },
            all: async (...params) => {
                const resultado = await pool.query(consulta, params);
                return resultado.rows;
            },
            run: async (...params) => {
                let sqlFinal = consulta;

                // O SQLite usava lastInsertRowid. No PostgreSQL usamos RETURNING id.
                if (/^\s*INSERT\s+INTO/i.test(sqlFinal) && !/\bRETURNING\b/i.test(sqlFinal)) {
                    sqlFinal += " RETURNING id";
                }

                try {
                    const resultado = await pool.query(sqlFinal, params);
                    return {
                        changes: resultado.rowCount,
                        lastInsertRowid: resultado.rows[0]?.id
                    };
                } catch (erro) {
                    if (erro.code === "23505") {
                        erro.message = `UNIQUE constraint failed: ${erro.detail || erro.message}`;
                    }
                    throw erro;
                }
            }
        };
    }

    async exec(sql) {
        return pool.query(sql);
    }
}

