function adminAutenticado(req, res, next) {

    const autorizacao =
        req.headers.authorization || "";

    const token =
        autorizacao.startsWith("Bearer ")
            ? autorizacao.substring(7)
            : "";

    if (!token || !sessoesAdmin.has(token)) {
        return res.status(401).json({
            erro: "Acesso não autorizado."
        });
    }

    next();
}

