app.get("/api/horarios", async (req, res) => {

    const { data } = req.query;

    if (!data) {
        return res.status(400).json({
            erro: "Informe a data."
        });
    }

    await limparReservasTemporarias();

    const agora = new Date();
    const horariosDisponiveis = [];

    for (const horario of schedule) {
        const dataHorario = new Date(`${data}T${horario}:00`);

        if (dataHorario.getTime() < agora.getTime() + (60 * 60 * 1000)) {
            continue;
        }

        const temporaria = await db.prepare(`
            SELECT id
            FROM reservas_temporarias
            WHERE data = ?
              AND horario = ?
              AND expira_em > ?
            LIMIT 1
        `).get(data, horario, Date.now());

        if (temporaria) continue;

        const confirmada = await db.prepare(`
            SELECT id
            FROM reservas
            WHERE data = ?
              AND horario = ?
              AND status = 'confirmada'
            LIMIT 1
        `).get(data, horario);

        if (confirmada) continue;

        const bloqueado = await db.prepare(`
            SELECT id
            FROM horarios_bloqueados
            WHERE data = ?
              AND horario = ?
            LIMIT 1
        `).get(data, horario);

        if (bloqueado) continue;

        horariosDisponiveis.push(horario);
    }

    res.json({
        data,
        horarios: horariosDisponiveis
    });
});

